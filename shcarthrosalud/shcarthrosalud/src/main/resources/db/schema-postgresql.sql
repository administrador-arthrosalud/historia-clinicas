-- Esquema de bd_archivos para PostgreSQL
-- Uso:
--   createdb -U postgres bd_archivos
--   psql -U postgres -d bd_archivos -f schema-postgresql.sql

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS historia_clinica (
    id_historia       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario        BIGINT       NOT NULL REFERENCES usuario (id_usuario),
    dni               VARCHAR(20)  NOT NULL UNIQUE,
    codigo_hc         VARCHAR(15)  NOT NULL UNIQUE,
    apellido_paterno  VARCHAR(50)  NOT NULL,
    apellido_materno  VARCHAR(50),
    nombres           VARCHAR(100) NOT NULL,
    fecha_registro    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_hc_apellido_paterno ON historia_clinica (apellido_paterno);
CREATE INDEX IF NOT EXISTS ix_hc_id_usuario ON historia_clinica (id_usuario);

-- Usuario inicial (el frontend registra con idUsuario = 1 mientras no haya login)
INSERT INTO usuario (nombre)
SELECT 'ADMIN'
WHERE NOT EXISTS (SELECT 1 FROM usuario);
